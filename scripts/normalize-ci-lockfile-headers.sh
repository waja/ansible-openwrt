#!/usr/bin/env bash
# shellcheck shell=bash
# scripts/normalize-ci-lockfile-headers.sh
set -eu

normalize_lockfile_header() {
  local lockfile="$1"
  local header
  local python_header_pattern
  local tmpfile

  header="$(sed -n '2p' "$lockfile")"
  if [[ "$header" == "# This file is autogenerated by pip-compile" ]]; then
    return 0
  fi

  python_header_pattern='^# This file is autogenerated by pip-compile'
  python_header_pattern+=' with Python [0-9]+\.[0-9]+$'
  if [[ ! "$header" =~ $python_header_pattern ]]; then
    echo "Unexpected pip-compile header in $lockfile" >&2
    return 1
  fi

  # Avoid sed -i: its syntax differs between GNU sed and BSD sed.
  local sed_expression
  sed_expression='2s|^# This file is autogenerated by pip-compile'
  sed_expression+=' with Python [0-9]+\\.[0-9]+
    rm -f "$tmpfile"
    return 1
  fi

  # Write back to the existing file to preserve its permissions.
  if ! cat "$tmpfile" > "$lockfile"; then
    rm -f "$tmpfile"
    return 1
  fi
  rm -f "$tmpfile"
}

main() {
  local lockfile
  if [ "$#" -gt 0 ]; then
    for lockfile in "$@"; do
      normalize_lockfile_header "$lockfile"
    done
  else
    for lockfile in \
      requirements/ci/ansible-test.txt \
      requirements/ci/lint.txt \
      requirements/ci/molecule.txt; do
      normalize_lockfile_header "$lockfile"
    done
  fi
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main "$@"
fi

  sed_expression+='|# This file is autogenerated by pip-compile|'
  tmpfile="$(mktemp "${lockfile}.XXXXXX")"
  if ! sed -E "$sed_expression" "$lockfile" > "$tmpfile"; then
    rm -f "$tmpfile"
    return 1
  fi

  # Write back to the existing file to preserve its permissions.
  if ! cat "$tmpfile" > "$lockfile"; then
    rm -f "$tmpfile"
    return 1
  fi
  rm -f "$tmpfile"
}

main() {
  local lockfile
  if [ "$#" -gt 0 ]; then
    for lockfile in "$@"; do
      normalize_lockfile_header "$lockfile"
    done
  else
    for lockfile in requirements/ci/ansible-test.txt requirements/ci/lint.txt requirements/ci/molecule.txt; do
      normalize_lockfile_header "$lockfile"
    done
  fi
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main "$@"
fi
